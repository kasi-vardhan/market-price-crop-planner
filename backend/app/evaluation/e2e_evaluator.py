import json
from pathlib import Path
from dotenv import load_dotenv

PROJECT_ROOT = Path(__file__).resolve().parents[3]
load_dotenv(PROJECT_ROOT / "backend" / ".env")
load_dotenv()

from app.services.plan_service import generate_crop_plan
from app.evaluation.consistency_checks import (
    evaluate_consistency,
)

TEST_CASE_PATH = (
    PROJECT_ROOT
    / "evaluation"
    / "e2e"
    / "e2e_test_cases.json"
)

RESULT_PATH = (
    PROJECT_ROOT
    / "evaluation"
    / "e2e"
    / "results.json"
)


def load_test_cases():
    with open(TEST_CASE_PATH, "r", encoding="utf-8") as file:
        return json.load(file)


def find_profit_results(tool_results):
    profits = []

    for item in tool_results:
        if not isinstance(item, dict):
            continue

        if item.get("tool") == "calculate_profit":
            result = item.get("result", {})

            if isinstance(result, dict):
                profits.append(result)

    return profits


def evaluate_case(test_case):
    result = {
        "id": test_case["id"],
        "status": "failed",
        "checks": {},
        "errors": []
    }

    try:
        graph_result = generate_crop_plan(
            farmer_question=test_case["farmer_question"],
            location=test_case["location"],
            soil=test_case["soil"],
            water=test_case["water"],
            season=test_case["season"],
            land_area=test_case["land_area"]
        )

        if not isinstance(graph_result, dict):
            raise TypeError(
                "Expected generate_crop_plan() to return a dictionary."
            )

        # Accommodate keys from plan_service ("recommendation" / "answer" and "ranking" / "ranking_result")
        answer = graph_result.get("recommendation") or graph_result.get("answer", "")
        tool_results = graph_result.get("tool_results", [])
        ranking = graph_result.get("ranking") or graph_result.get("ranking_result", {})
        citations = graph_result.get("source_citations", [])

        consistency = evaluate_consistency(
            answer=answer,
            ranking=ranking,
            tool_results=tool_results,
            citations=citations,
        )

        result["consistency"] = consistency

        result["checks"]["pipeline_returned_data"] = True
        result["checks"]["answer_present"] = bool(
            isinstance(answer, str) and answer.strip()
        )
        result["checks"]["ranking_present"] = bool(ranking)
        result["checks"]["citations_are_list"] = isinstance(
            citations, list
        )

        # The ranking must come from the deterministic ranking node.
        recommended_crop = ranking.get("recommended_crop")

        if recommended_crop is None:
            # Some implementations store the top crop in candidates.
            candidates = ranking.get("ranked_crops", [])

            if candidates and isinstance(candidates[0], dict):
                recommended_crop = candidates[0].get("crop")

        result["recommended_crop"] = recommended_crop

        result["checks"]["recommendation_available"] = bool(
            recommended_crop
        )

        # Check that reported financial values are available
        # from deterministic tools rather than generated by the LLM.
        profit_results = find_profit_results(tool_results)

        result["checks"]["profit_tool_returned_data"] = bool(
            profit_results
        )

        result["profit_results"] = profit_results
        result["citation_count"] = len(citations)

        # Preserve the full answer for manual review.
        result["answer"] = answer

        result["status"] = "completed"

    except Exception as exc:
        result["errors"].append(
            f"{type(exc).__name__}: {exc}"
        )

    return result


import time


def run_evaluation():
    test_cases = load_test_cases()
    results = []

    for test_case in test_cases:
        print(f"Running {test_case['id']}...")

        results.append(evaluate_case(test_case))
        time.sleep(10)

    completed = [
        item for item in results
        if item["status"] == "completed"
    ]

    report = {
        "evaluation": "End-to-End Agriculture Agent Evaluation",
        "total_cases": len(results),
        "completed_cases": len(completed),
        "failed_cases": len(results) - len(completed),
        "completion_rate": (
            round(len(completed) / len(results), 4)
            if results else 0
        ),
        "cases": results
    }

    RESULT_PATH.parent.mkdir(parents=True, exist_ok=True)

    with open(RESULT_PATH, "w", encoding="utf-8") as file:
        json.dump(report, file, indent=2, ensure_ascii=False)

    return report


if __name__ == "__main__":
    report = run_evaluation()

    print("\n===== END-TO-END EVALUATION =====")
    print(f"Total cases: {report['total_cases']}")
    print(f"Completed: {report['completed_cases']}")
    print(f"Failed: {report['failed_cases']}")
    print(f"Completion rate: {report['completion_rate']}")

    print(f"\nReport saved to: {RESULT_PATH}")
